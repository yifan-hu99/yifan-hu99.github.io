import { test,expect } from '@playwright/test';
const parseEvents=(text:string)=>text.trim().split('\n').map(line=>JSON.parse(line));
test('one conversation permits followups; a new conversation requires confirmed background',async({page,request})=>{
 await page.goto('/');
 const gate=page.getByRole('dialog',{name:'Complete your profile before a new chat'});
 await expect(gate).not.toBeVisible();
 await page.getByRole('textbox',{name:'Describe the opportunities you want'}).fill('Find AI FDE opportunities');
 await expect(page.getByRole('button',{name:'Send search'})).toBeEnabled();
 if(await page.getByRole('button',{name:'Live search',exact:true}).count())await page.getByRole('button',{name:'Live search',exact:true}).click();
 await expect(page.getByRole('button',{name:'Demo workspace',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Send search'}).click();
 await expect(page.locator('.opportunity')).toHaveCount(3);
 await expect(gate).toBeVisible();
 await gate.getByRole('button',{name:'Continue this chat and explore results'}).click();
 const id=await page.evaluate(()=>localStorage.getItem('cambium.currentConversation'));
 const before=(await (await request.get('/api/conversations')).json()).length;
 const next=await request.post('/api/chat',{data:{message:'Find a different AI role',demo:true}});
 expect(next.status()).toBe(403);expect((await next.json()).error.code).toBe('PROFILE_REQUIRED');
 const followup=await request.post('/api/chat',{data:{conversationId:id,message:'Make these more startup focused',demo:true}});
 expect(followup.status()).toBe(200);
 expect((await (await request.get('/api/conversations')).json()).length).toBe(before);
 await page.goto('/');
 await expect(gate).not.toBeVisible();
 await page.evaluate(()=>localStorage.removeItem('cambium.currentConversation'));await page.reload();
 await expect(gate).not.toBeVisible();await expect(page.locator('.opportunity')).toHaveCount(6);
 const nav=page.getByRole('navigation',{name:'Main navigation'});expect((await nav.boundingBox())!.y).toBeLessThan(130);
 await page.getByRole('button',{name:'Find AI FDE opportunities',exact:true}).click();
 const card=page.locator('.opportunity').first();await expect(card.locator('.brief-section')).toHaveCount(0);await expect(card.locator('.opportunity-highlights>div')).toHaveCount(3);await card.getByRole('button',{name:'View details',exact:true}).click();await expect(card.locator('.brief-section')).toHaveCount(6);
 await expect(card.locator('.brief-accordion[open]')).toHaveCount(0);
 expect((await card.locator('.opportunity-brief').boundingBox())!.height).toBeLessThan(360);
 await card.locator('.brief-accordion').nth(0).locator('summary').first().click();
 await card.locator('.brief-accordion').nth(1).locator('summary').first().click();
 await expect(card.locator('.brief-accordion[open]')).toHaveCount(1);
 for(const heading of ['Why this','Why you','Why now','Practical details','Contact routes','Next action'])await expect(card.getByRole('heading',{name:new RegExp(heading)})).toBeVisible();
 await page.getByRole('button',{name:/New chat/}).click();await expect(gate).toBeVisible();
 await gate.getByRole('button',{name:'Add portfolio / complete profile'}).click();
 await page.getByLabel('Skills & strengths',{exact:false}).fill('Python, applied AI');
 await page.getByLabel('Portfolio or personal site').fill('https://portfolio.example/work');
 await page.getByLabel('Use confirmed skills for matching').check();
 await page.getByRole('button',{name:'Confirm & save profile'}).click();
 await expect(page.getByText('Profile confirmed. You can start a new chat; opportunity matching has been updated.')).toBeVisible();
 await expect(page.getByRole('dialog',{name:'Complete your profile before a new chat'})).not.toBeVisible();
 const after=await request.post('/api/chat',{data:{message:'Find remote AI projects',demo:true}});
 expect(after.status()).toBe(200);const newId=parseEvents(await after.text()).find(e=>e.type==='conversation').id;expect(newId).not.toBe(id);
});
